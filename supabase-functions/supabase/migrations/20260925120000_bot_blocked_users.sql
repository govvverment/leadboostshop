-- Отслеживание пользователей, заблокировавших Telegram-бота — нужно
-- для статистики в админке ("сколько реально достижимы рассылкой").
--
-- Два источника обновления этого флага:
--  1) Автоматически, "живьём" — bot-webhook ловит my_chat_member-апдейт
--     (Telegram шлёт его сам, когда пользователь блокирует/разблокирует
--     бота) и сразу обновляет строку. Работает только для событий ПОСЛЕ
--     того, как это было включено.
--  2) Вручную, по кнопке в админке ("Обновить" в статистике) — новый
--     action 'refresh-blocked' в admin-stats проходит по ВСЕМ
--     пользователям через Bot API (getChatMember) и пересчитывает флаг
--     заново. Это и бэкафилл для пользователей, заблокировавших бота ещё
--     до появления вебхука, и подстраховка на случай, если сам вебхук
--     на какое-то время не работал.
alter table users add column if not exists bot_blocked boolean not null default false;
alter table users add column if not exists bot_blocked_checked_at timestamptz;
