// Склонение по числу. У ru/uk одна и та же славянская схема (1/2-4/5-...,
// с исключением на 11-14), у en — обычная (1 / не 1). forms — массив слов:
// для ru/uk длина 3 ([один, два-четыре, пять+]), для en длина 2 ([ед., мн.]).
export function pluralize(locale, n, forms) {
  if (!forms) return '';
  if (locale === 'en') {
    return n === 1 ? forms[0] : forms[1];
  }
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return forms[0];
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 10 || mod100 >= 20)) return forms[1];
  return forms[2];
}

